/**
 * 민감도 축. 슬라이더가 정하는 것은 "어느 길이의 봉으로 보는가"다.
 *
 * 사용자 요구가 명확했다 — 판정 기준이 특정 봉(15분)에 고정되어서는 안 되고,
 * 시간봉은 판정 축이 아니라 "이 위치에 두면 이 봉급을 본다"는 참고 라벨이다.
 * 그래서 슬라이더가 봉 길이를 움직이고 배수는 거기서 따라 나온다.
 *
 * 왼쪽이 조용하고(긴 봉, 드문 사건) 오른쪽이 잦다(짧은 봉, 잦은 사건).
 *
 * 규칙은 하나다 — **배수 3.5배 고정, 1분봉만 예외.**
 *
 * 3.5배는 사용자가 선물 5분봉 차트 이틀치(2026-08-02~03, 표시 14개)에
 * 직접 표시한 것을 100% 잡는 값이다. 유일하게 선물에서 검증된 숫자이고,
 * 나머지 봉은 같은 배수를 그대로 적용했다.
 *
 * 그래도 되는 이유: 3.5배를 모든 봉에 걸면 빈도가 저절로 벌어진다.
 *   4h 0.28  →  1h 1.19  →  15m 4.84  →  5m 14.06
 * 한 칸에 약 4배씩이라 슬라이더 한 칸이 실제로 다른 설정이 된다. 봉마다
 * 배수를 따로 정할 근거가 없었고, 실측해 보니 필요도 없었다.
 *
 * 1분봉만 예외인 이유: 짧은 봉은 원래 심하게 튄다. 3.5배를 그대로 걸면
 * 하루 82회가 되어 다른 봉과 간격이 무너진다. 한 칸 간격(약 3.5배)을
 * 유지하는 5.0배를 쓴다 → 하루 50회.
 *
 * 폐기한 것: 목표 빈도(0.3/1/4.2/10/30)를 먼저 정하고 배수를 역산하던
 * 방식. 그 다섯 숫자가 라운드 넘버였을 뿐 근거가 없었고, 사용자가 실제
 * 표시한 5분봉 빈도(하루 14회)와도 어긋났다. 지금은 배수가 근거이고
 * 빈도가 결과다.
 *
 * 측정: USD-M 선물 대형주 3종목(BTC/ETH/SOL), 2026-05-01~07-31에서 예열
 * 30일을 뺀 62일. 원본은 일별 aggTrades를 1초 버킷으로 묶은 것이다.
 * 현물로 쟀던 값은 전부 폐기했다 (detector/src/binance.ts 주석 참고).
 *
 * 1일봉이 없는 이유는 § 아래 SCALE_TIMEFRAMES 주석 참고.
 */
export interface SensitivityScale {
  /** 이 위치에서 판정에 쓰는 창 길이. 규모 라벨도 이 값이다. */
  timeframe: Timeframe;
  /** 그 창의 거래대금이 직전 창들 중앙값의 몇 배면 알리는가. */
  ratio: number;
  /** 대형주 기준 코인 1개당 하루 알림 수. 실측값이다. */
  alertsPerDay: number;
}

