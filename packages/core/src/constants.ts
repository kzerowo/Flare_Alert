/**
 * 슬라이더에 올릴 수 있는 봉 길이. 1일봉은 없다.
 *
 * 하루치 거래대금은 어떤 사건이 와도 평소의 3배가 되지 않는다. 61일 동안
 * 대형주 3종목에서 한 번도 없었고, 배수를 1.1배까지 내려도 하루 0.12회다.
 * 하루를 통째로 합치면 급등 30분이 나머지 23시간 반에 희석된다.
 *
 * TIMEFRAMES에는 여전히 1d가 있다. 집계기는 여섯 프레임을 다 계산하고,
 * 알림에 붙는 규모 라벨로는 쓸 수 있기 때문이다. 다만 슬라이더가 그 자리에
 * 설 수는 없다.
 */
